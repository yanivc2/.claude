/** הזזת כיול (מ"מ) — מדפסת שמזיזה את הדף מעט. מוגבל ל-±15 מ"מ: מעבר לזה זו טעות הקלדה, לא כיול. */
export function normalizeOffset(raw) {
  const n = (v) => {
    const x = Number(String(v ?? '').replace(',', '.'));
    return Number.isFinite(x) ? Math.max(-15, Math.min(15, Math.round(x * 10) / 10)) : 0;
  };
  return { dx: n(raw?.dx), dy: n(raw?.dy) };
}

/**
 * שורות טבלת "פרטים": שורה לכל חשבונית/זיכוי בתשלום. אם יש יותר ממה שנכנס — השורות האחרונות מתקבצות
 * לשורה אחת "ועוד N" עם הסכום שלהן, כדי שהסה"כ בטבלה תמיד יתאים לצ׳ק.
 */
export function detailRows(lines, maxRows = MAX_ROWS) {
  if (lines.length <= maxRows) return lines;
  const keep = lines.slice(0, maxRows - 1);
  const rest = lines.slice(maxRows - 1);
  return [...keep, { text: `ועוד ${rest.length} מסמכים`, amount: rest.reduce((s, l) => s + l.amount, 0) }];
}
